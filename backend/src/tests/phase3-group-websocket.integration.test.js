import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import WebSocket from 'ws';
import { sql } from 'drizzle-orm';
import { buildApp } from '../app.js';
import { loadEnv } from '../config/env.js';
import { users } from '../database/schema/index.js';
import { hashPassword } from '../services/password.service.js';
import { authService } from '../modules/auth/auth.service.js';
import { accessToken } from '../services/token.service.js';

const testUrl = process.env.TEST_DATABASE_URL;
const enabled = testUrl && new URL(testUrl).pathname.endsWith('_test');
const wait = (socket, event, predicate = () => true) => new Promise((resolve, reject) => {
  const timer = setTimeout(() => reject(new Error(`Timed out: ${event}`)), 3000);
  const listener = (raw) => { const data = JSON.parse(raw); if (data.event === event && predicate(data)) { clearTimeout(timer); socket.off('message', listener); resolve(data); } };
  socket.on('message', listener);
});
const open = async (url, token) => {
  const socket = new WebSocket(url, { headers: { authorization: `Bearer ${token}` } });
  await new Promise((resolve, reject) => { socket.once('open', resolve); socket.once('error', reject); });
  await wait(socket, 'connection.ready');
  return socket;
};
test('Phase 3 Batch 2A: group WebSocket authorization and fan-out', { skip: !enabled && 'Set TEST_DATABASE_URL ending in _test' }, async (t) => {
  const config = loadEnv({ NODE_ENV: 'test', LOG_LEVEL: 'silent', DATABASE_URL: testUrl, JWT_SECRET: 'group-ws-secret-'.repeat(5) });
  const app = await buildApp({ config }); t.after(() => app.close());
  await app.database.db.execute(sql`truncate table audit_logs, consumed_refresh_tokens, sessions, devices, users restart identity cascade`);
  const hash = await hashPassword('Group-Ws-Password-9!');
  const people = await app.database.db.insert(users).values(['ownerws', 'memberws', 'removedws', 'outsiderws'].map((username) => ({ username, displayName: username, passwordHash: hash, mustChangePassword: false }))).returning();
  const auth = authService(app, config);
  const login = (user, device) => auth.login({ username: user.username, password: 'Group-Ws-Password-9!', clientType: 'native', platform: 'android', deviceName: device }, { ip: '127.0.0.1' });
  const [owner, member1, member2, removed, outsider] = await Promise.all([login(people[0], 'owner'), login(people[1], 'member1'), login(people[1], 'member2'), login(people[2], 'removed'), login(people[3], 'outsider')]);
  const token = (x) => accessToken(app, x.user, x.session); const header = { authorization: `Bearer ${token(owner)}` };
  const address = await app.listen({ host: '127.0.0.1', port: 0 }); const url = address.replace('http:', 'ws:') + '/api/v1/ws';
  const [ownerSocket, memberSocket1, memberSocket2, removedSocket, outsiderSocket] = await Promise.all([open(url, token(owner)), open(url, token(member1)), open(url, token(member2)), open(url, token(removed)), open(url, token(outsider))]);
  t.after(() => [ownerSocket, memberSocket1, memberSocket2, removedSocket, outsiderSocket].forEach((s) => s.terminate()));
  const createdEvent = wait(ownerSocket, 'conversation.created');
  const group = (await app.inject({ method: 'POST', url: '/api/v1/groups', headers: header, payload: { title: 'Socket group' } })).json();
  const creation = await createdEvent;
  assert.equal(creation.data.id, group.id); assert.equal(creation.data.createdBy, people[0].id);
  const added1 = wait(memberSocket1, 'group.member_added'); const added2 = wait(memberSocket2, 'group.member_added');
  assert.equal((await app.inject({ method: 'POST', url: `/api/v1/groups/${group.id}/members`, headers: header, payload: { userId: people[1].id } })).statusCode, 201);
  assert.equal((await added1).data.userId, people[1].id); assert.equal((await added2).data.userId, people[1].id);
  assert.equal((await app.inject({ method: 'POST', url: `/api/v1/groups/${group.id}/members`, headers: header, payload: { userId: people[2].id } })).statusCode, 201);
  const update1 = wait(memberSocket1, 'conversation.updated'); const update2 = wait(memberSocket2, 'conversation.updated');
  await app.inject({ method: 'PATCH', url: `/api/v1/groups/${group.id}`, headers: header, payload: { title: 'Updated group' } });
  assert.equal((await update1).data.id, group.id); assert.equal((await update2).data.id, group.id);
  const removal = wait(removedSocket, 'group.member_removed');
  await app.inject({ method: 'DELETE', url: `/api/v1/groups/${group.id}/members/${people[2].id}`, headers: header });
  assert.equal((await removal).data.conversationId, group.id);
  const message1 = wait(memberSocket1, 'message.created', (event) => event.data.content === 'members only'); const message2 = wait(memberSocket2, 'message.created', (event) => event.data.content === 'members only');
  const sent = await app.inject({ method: 'POST', url: `/api/v1/conversations/${group.id}/messages`, headers: header, payload: { clientMessageId: randomUUID(), content: 'members only' } });
  assert.equal((await message1).data.id, sent.json().id); assert.equal((await message2).data.id, sent.json().id);
  const transfer = wait(memberSocket1, 'group.owner_transferred');
  const transferMessage = wait(memberSocket2, 'message.created', (event) => event.data.content === 'Group ownership was transferred');
  assert.equal((await app.inject({ method: 'POST', url: `/api/v1/groups/${group.id}/transfer-owner`, headers: header, payload: { userId: people[1].id } })).statusCode, 200);
  assert.equal((await transfer).data.userId, people[1].id);
  assert.equal((await transferMessage).data.messageType, 'system');
  assert.equal(outsiderSocket.readyState, WebSocket.OPEN);
});

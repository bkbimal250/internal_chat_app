import { test, expect } from '@playwright/test'
import { loadAccounts, login, openConversation, openNewChat, sendMessage, workspaceNav } from './helpers.js'

test.describe('Responsive navigation', () => {
  test('keeps the desktop rail, list, and chat pane together', async ({ page }) => {
    const accounts = loadAccounts()
    await page.setViewportSize({ width: 1440, height: 900 })
    await login(page, accounts.alpha)
    await expect(page.getByTestId('workspace-rail')).toBeVisible()
    await expect(page.getByTestId('conversation-sidebar')).toBeVisible()
    const handle = page.getByTestId('sidebar-resize-handle')
    await expect(handle).toBeVisible()
    const sidebar = page.getByTestId('conversation-sidebar')
    const start = await sidebar.boundingBox()
    const handleBox = await handle.boundingBox()
    await page.mouse.move(handleBox.x + handleBox.width / 2, handleBox.y + handleBox.height / 2)
    await page.mouse.down()
    await page.mouse.move(start.x + start.width + 90, handleBox.y + handleBox.height / 2, { steps: 12 })
    await page.mouse.up()
    const stretched = await sidebar.boundingBox()
    expect(stretched.width).toBeGreaterThan(start.width + 20)
    const stretchedHandle = await handle.boundingBox()
    await page.mouse.move(stretchedHandle.x + stretchedHandle.width / 2, stretchedHandle.y + stretchedHandle.height / 2)
    await page.mouse.down()
    await page.mouse.move(start.x + 220, stretchedHandle.y + stretchedHandle.height / 2, { steps: 12 })
    await page.mouse.up()
    const shrunk = await sidebar.boundingBox()
    expect(shrunk.width).toBeLessThan(stretched.width - 20)
    await expect(workspaceNav(page, 'People')).toBeVisible()
    await expect(workspaceNav(page, 'Groups')).toBeVisible()
    await expect(workspaceNav(page, 'Settings')).toBeVisible()
    await workspaceNav(page, 'People').click()
    await expect(page.getByRole('heading', { name: 'Employee directory' })).toBeVisible()
    await expect(page).toHaveURL('http://127.0.0.1:5173/')
    await workspaceNav(page, 'Chats').click()
    await expect(page.getByTestId('chats-heading')).toBeVisible()
    await expect(page).toHaveURL('http://127.0.0.1:5173/')
  })

  test('uses a hamburger shell on tablet while keeping list and chat', async ({ page }) => {
    const accounts = loadAccounts()
    await page.setViewportSize({ width: 800, height: 1024 })
    await login(page, accounts.alpha)
    await expect(page.getByTestId('workspace-rail')).toBeHidden()
    await expect(page.getByRole('button', { name: 'Open navigation' })).toBeVisible()
    await expect(page.getByTestId('conversation-sidebar')).toBeVisible()
    await expect(page.getByTestId('sidebar-resize-handle')).toBeVisible()
    await page.getByRole('button', { name: 'Open navigation' }).click()
    await expect(workspaceNav(page, 'Settings')).toBeVisible()
    await workspaceNav(page, 'Settings').click()
    await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
    await expect(page).toHaveURL('http://127.0.0.1:5173/')
  })

  test('splits conversation list and chat on mobile with back navigation', async ({ page }) => {
    const accounts = loadAccounts()
    await page.setViewportSize({ width: 390, height: 844 })
    await login(page, accounts.alpha)
    await expect(page.getByTestId('conversation-sidebar')).toBeVisible()
    await expect(page.getByTestId('sidebar-resize-handle')).toHaveCount(0)
    await expect(page.getByTestId('message-pane')).toHaveCount(0)
    await openNewChat(page, accounts.charlie.displayName)
    await expect(page.getByTestId('message-pane')).toBeVisible()
    await expect(page.getByTestId('conversation-sidebar')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Back to chats' })).toBeVisible()
    await expect(page).toHaveURL('http://127.0.0.1:5173/')
    await sendMessage(page, `mobile-${Date.now()}`)
    await page.getByRole('button', { name: 'Back to chats' }).click()
    await expect(page.getByTestId('conversation-sidebar')).toBeVisible()
    await expect(page.getByTestId('message-pane')).toHaveCount(0)
    await openConversation(page, accounts.charlie.displayName)
    await expect(page.getByTestId('message-pane')).toBeVisible()
    await expect(page).toHaveURL('http://127.0.0.1:5173/')
  })
})
